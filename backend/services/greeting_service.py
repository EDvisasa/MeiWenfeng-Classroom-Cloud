def get_time_slot(now: Optional[datetime] = None) -> str:
    """计算当前现实物理时段 (6 档)"""
    if now is None:
        now = datetime.now()
    hour = now.hour

    if 6 <= hour < 9:
        return "dawn"        # 晨曦梳妆 (06:00 - 08:59)
    elif 9 <= hour < 12:
        return "morning"     # 上午清神 (09:00 - 11:59)
    elif 12 <= hour < 17:
        return "afternoon"   # 午后春困 (12:00 - 16:59)
    elif 17 <= hour < 20:
        return "dusk"        # 傍晚归家 (17:00 - 19:59)
    elif 20 <= hour < 23:
        return "evening"     # 夜阑伴读 (20:00 - 22:59)
    else:
        return "midnight"    # 子夜心疼 (23:00 - 05:59)


