class GreetingService:
    """开场白编排服务：执行 A × B × C × D 笛卡尔积合成"""

    @staticmethod
    def generate_greeting(
        affection: Optional[int] = None,
        now: Optional[datetime] = None,
        force_reunion: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        生成极具画面感的生活化开场白。
        
        Args:
            affection: 指定好感度，若为 None 则从 CharacterStateManager 实时读取并结算衰减
            now: 指定时间，默认当前时间
            force_reunion: 强制指定重逢级别 ("light", "medium", "heavy", "none")
        """
        if now is None:
            now = datetime.now()

        # 1. 维度 B: 物理时段
        time_slot = get_time_slot(now)

        # 2. 维度 A & C: 好感阶段与久别重逢状态
        reunion_type = force_reunion
        if affection is None:
            # 惰性结算衰减并读取真实状态
            state, reunion_info = CharacterStateManager.evaluate_temporal_decay(now=now)
            affection = state.affection

            if force_reunion is None and reunion_info:
                days = reunion_info.get("absent_days", 0)
                if days <= 7:
                    reunion_type = "light"
                elif days <= 20:
                    reunion_type = "medium"
                else:
                    reunion_type = "heavy"
        else:
            if force_reunion is None:
                reunion_type = "none"

        stage = CharacterStateManager.get_stage(affection)

        # 3. 维度 D: 抽取原版生活行为
        vignette_candidates = ORIGINAL_VIGNETTES.get(time_slot, ORIGINAL_VIGNETTES["morning"])
        selected_vignette = random.choice(vignette_candidates)
        ambient_text = selected_vignette["ambient"]

        # 4. 抽取面相过渡动作
        transition_candidates = TRANSITION_ACTIONS.get(stage, TRANSITION_ACTIONS[3])
        transition_action = random.choice(transition_candidates)

        # 5. 抽取切合心境与重逢状态的首句台词
        if reunion_type and reunion_type in REUNION_OVERRIDE_DIALOGUES:
            dialogue_text = REUNION_OVERRIDE_DIALOGUES[reunion_type].get(stage, "夫君，你可算来了。")
        else:
            stage_dialogues = ROUTINE_DIALOGUES.get(stage, ROUTINE_DIALOGUES[3])
            slot_dialogues = stage_dialogues.get(time_slot, stage_dialogues.get("morning", ["夫君，你可算来了。"]))
            dialogue_text = random.choice(slot_dialogues)

        # 6. 四元槽位合成 (Slot-Filling)
        content = f"*（{ambient_text}。{transition_action}）*“{dialogue_text}”"

        return {
            "role": "assistant",
            "content": content,
            "timestamp": now.strftime("%Y-%m-%dT%H:%M:%S"),
            "meta": {
                "time_slot": time_slot,
                "stage": stage,
                "affection": affection,
                "reunion_type": reunion_type or "none",
                "item": selected_vignette.get("item", "")
            }
        }
